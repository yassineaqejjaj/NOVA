const VALUES_FR_FEMININE: Record<string, string> = { medium: "moyenne", high: "élevée", open: "ouverte", resolved: "résolue", blocked: "bloquée", answered: "répondue" };
const FEMININE_FIELDS = new Set(["confidence", "likelihood", "severity", "influence"]);

const humanize = (key: string) => key.replaceAll("_", " ");

export function kindLabel(kind: string, lang: Lang): string {
  return (lang === "fr" && KINDS_FR[kind]) || humanize(kind);
}

export function fieldLabel(field: string, lang: Lang): string {
  return (lang === "fr" && FIELDS_FR[field]) || humanize(field);
}

export function valueLabel(field: string, value: string, lang: Lang): string {
  if (lang !== "fr") return humanize(value);
  return (FEMININE_FIELDS.has(field) && VALUES_FR_FEMININE[value]) || VALUES_FR[value] || humanize(value);
}
